    /// <summary>The analyser's label: the RC band, plus " || " and the LN band when holds are 15 % or more</summary>
    public static string? Label(double sr, double lnRatio, int keys, bool extended)
    {
        var (rc, ln) = Split(sr, lnRatio, keys, extended);
        return rc == null ? null : ln == null ? rc : $"{rc} || {ln}";
    }

    /// <summary>The RC band, and the LN band when the chart is 15 % holds or more (null when there's no table)</summary>
    public static (string? Rc, string? Ln) Split(double sr, double lnRatio, int keys, bool extended)
    {
        if (!double.IsFinite(sr) || Table(keys, false, extended) is not { } rcTable) return (null, null);
        var rc = Lookup(sr, rcTable);
        return lnRatio < 0.15 || Table(keys, true, extended) is not { } lnTable ? (rc, null) : (rc, Lookup(sr, lnTable));
    }

    private static string Lookup(double sr, Band[] table)
    {
        foreach (var b in table)
            if (b.Lower <= sr && sr <= b.Upper) return b.Name;
        if (sr < table[0].Lower) return $"< {table[0].Name}";
        if (sr > table[^1].Upper) return $"> {table[^1].Name}";
        return "Unknown";
    }

    /// <summary>A band's dan without its low / mid / high part ("Reform 3 mid/high" -> "Reform 3", "Alpha Low" -> "Alpha")</summary>
    public static string Dan(string band)
    {
        foreach (var part in new[] { " mid/low", " mid/high", " low", " mid", " high" })
            if (band.EndsWith(part, StringComparison.OrdinalIgnoreCase)) return band[..^part.Length];
        return band;
    }

    /// <summary>The dans of a table in order, for folders</summary>
    public static string[] DanOrder(int keys, bool ln, bool extended) =>
        Table(keys, ln, extended)?.Select(b => Dan(b.Name)).Distinct().ToArray() ?? [];
